CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    asset_number VARCHAR(80) NOT NULL,
    name VARCHAR(160) NOT NULL,
    type VARCHAR(80) NOT NULL,
    description VARCHAR(2000),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_assets_organization FOREIGN KEY (organization_id)
        REFERENCES organizations (id) ON DELETE RESTRICT,
    CONSTRAINT ck_assets_asset_number_not_blank CHECK (length(btrim(asset_number)) > 0),
    CONSTRAINT ck_assets_name_not_blank CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_assets_type_not_blank CHECK (length(btrim(type)) > 0),
    CONSTRAINT ck_assets_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE UNIQUE INDEX ux_assets_organization_asset_number_lower
    ON assets (organization_id, lower(asset_number));

CREATE INDEX ix_assets_organization_status_type
    ON assets (organization_id, status, lower(type));

CREATE INDEX ix_assets_organization_name_id
    ON assets (organization_id, name, id);
