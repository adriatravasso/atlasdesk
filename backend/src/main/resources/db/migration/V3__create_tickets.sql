CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    requester_id BIGINT NOT NULL,
    assigned_agent_id BIGINT,
    asset_id BIGINT,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    CONSTRAINT fk_tickets_organization FOREIGN KEY (organization_id)
        REFERENCES organizations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_requester FOREIGN KEY (requester_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_assigned_agent FOREIGN KEY (assigned_agent_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_asset FOREIGN KEY (asset_id)
        REFERENCES assets (id) ON DELETE RESTRICT,
    CONSTRAINT ck_tickets_title_not_blank CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_tickets_description_not_blank CHECK (length(btrim(description)) > 0),
    CONSTRAINT ck_tickets_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_tickets_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'PENDING_APPROVAL', 'RESOLVED', 'CLOSED'))
);

CREATE INDEX ix_tickets_organization_status_created
    ON tickets (organization_id, status, created_at DESC, id DESC);

CREATE INDEX ix_tickets_organization_created
    ON tickets (organization_id, created_at DESC, id DESC);

CREATE INDEX ix_tickets_organization_requester_created
    ON tickets (organization_id, requester_id, created_at DESC, id DESC);
