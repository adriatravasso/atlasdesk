CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    require_approval BOOLEAN NOT NULL DEFAULT FALSE,
    sla_low_hours INTEGER NOT NULL DEFAULT 72,
    sla_medium_hours INTEGER NOT NULL DEFAULT 24,
    sla_high_hours INTEGER NOT NULL DEFAULT 4,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_organizations_name_not_blank CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_organizations_sla_low_positive CHECK (sla_low_hours > 0),
    CONSTRAINT ck_organizations_sla_medium_positive CHECK (sla_medium_hours > 0),
    CONSTRAINT ck_organizations_sla_high_positive CHECK (sla_high_hours > 0)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_users_organization FOREIGN KEY (organization_id)
        REFERENCES organizations (id) ON DELETE RESTRICT,
    CONSTRAINT ck_users_name_not_blank CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_users_email_not_blank CHECK (length(btrim(email)) > 0),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'AGENT', 'REQUESTER'))
);

CREATE UNIQUE INDEX ux_users_organization_email_lower
    ON users (organization_id, lower(email));
