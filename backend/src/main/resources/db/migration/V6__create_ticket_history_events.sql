CREATE TABLE ticket_history_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    ticket_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    actor_name VARCHAR(160) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    description VARCHAR(240) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    ticket_version BIGINT NOT NULL,
    CONSTRAINT fk_ticket_history_organization FOREIGN KEY (organization_id)
        REFERENCES organizations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ticket_history_ticket FOREIGN KEY (ticket_id)
        REFERENCES tickets (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ticket_history_actor FOREIGN KEY (actor_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ticket_history_type CHECK (event_type IN (
        'CREATED', 'ASSIGNED', 'STARTED', 'RESOLUTION_REQUESTED',
        'RESOLVED', 'APPROVED', 'REJECTED', 'CLOSED'
    )),
    CONSTRAINT ck_ticket_history_description_not_blank CHECK (length(btrim(description)) > 0),
    CONSTRAINT uq_ticket_history_ticket_version UNIQUE (ticket_id, ticket_version)
);

CREATE INDEX ix_ticket_history_organization_ticket_time
    ON ticket_history_events (organization_id, ticket_id, occurred_at, id);

INSERT INTO ticket_history_events (
    organization_id, ticket_id, actor_id, actor_name, event_type, description, occurred_at, ticket_version
)
SELECT ticket.organization_id, ticket.id, requester.id, requester.name, 'CREATED',
    'Chamado criado', ticket.created_at, 0
FROM tickets ticket
JOIN users requester ON requester.id = ticket.requester_id;
